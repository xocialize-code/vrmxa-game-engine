// The local fix for @pixiv/three-vrm 3.5.5's MToonNodeMaterial on three r187 (AB-T-0553).
//
// three r187 removed the deprecated `transformedNormalView` export from three/tsl (mrdoob/three.js#34517);
// it had been renamed `normalView` in r178 (mrdoob/three.js#31271). three-vrm 3.5.5 still imports the old
// name in two places (the MToon lighting model's dotNL and the parametric rim's dotNV), so the module fails
// to link: pixiv/three-vrm#1889. The fix is upstream PR pixiv/three-vrm#1890 (open, not released).
//
// It writes two copies of @pixiv/three-vrm/lib/nodes/index.module.js (keeping pixiv's MIT notices):
//
// src/vendor/three-vrm-nodes-loadonly.js: the LOAD fix only, those two imports pointed at `normalView`.
//   That is #1890's r178+ branch, the only branch that runs on r187.
//
// src/vendor/three-vrm-nodes.js: the load fix plus three FIDELITY fixes, so MToonNodeMaterial renders like
//   the GLSL MToonMaterial that WebGLRenderer uses (measured in this spike; none is r187-specific, all
//   three are in 3.5.5 on any three revision):
//   1. matcap UV: `matcapUV.mul(1, -1).add(0, 1)` is 1 − uv on BOTH axes, because TSL's mul/add are
//      variadic (a.mul(1, -1) is a·1·−1, not a·vec2(1, −1)). The V flip is intended; the U flip mirrors the
//      matcap left↔right. Fixed with vec2 operands.
//   2. rim view direction: the parametric rim uses `modelViewPosition`, which in TSL is the OBJECT's origin
//      in view space (a per-object uniform), not the fragment's position. The rim's N·V is computed against
//      one direction per mesh (for a VRM, towards its feet). Fixed with `positionView` (per fragment), as
//      the GLSL uses vViewPosition.
//   3. rim lighting mix: GLSL mixes the rim towards (direct + ambient irradiance) / π; the node model leaves
//      the ambient irradiance out (it mixes towards 0 in indirectSpecular). Fixed by mixing towards
//      BRDF_Lambert(irradiance) there.
//
// --check: exit 1 if the stock file no longer matches (a new three-vrm release), so the patch is not
// applied blindly.
import fs from 'node:fs';
import path from 'node:path';

const here = import.meta.dirname;
const web = path.resolve(here, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(web, 'node_modules/@pixiv/three-vrm/package.json'), 'utf8'));
const src = path.join(web, 'node_modules/@pixiv/three-vrm/lib/nodes/index.module.js');
const outFull = path.join(web, 'src/vendor/three-vrm-nodes.js');
const outLoad = path.join(web, 'src/vendor/three-vrm-nodes-loadonly.js');

const loadEdits = [
  [
    'import { BRDF_Lambert, diffuseColor, float, mix, transformedNormalView, vec3 } from "three/tsl";',
    'import { BRDF_Lambert, diffuseColor, float, mix, normalView as transformedNormalView, vec3 } from "three/tsl"; // VRMXG patch: r187 removed transformedNormalView (pixiv/three-vrm#1890)',
  ],
  [
    'import { float as float2, modelViewPosition, transformedNormalView as transformedNormalView2 } from "three/tsl";',
    'import { float as float2, modelViewPosition, normalView as transformedNormalView2 } from "three/tsl"; // VRMXG patch: r187 removed transformedNormalView (pixiv/three-vrm#1890)',
  ],
];
const fidelityEdits = [
  [
    'const map = refMatcapTexture.context({ getUV: () => matcapUV.mul(1, -1).add(0, 1) });',
    'const map = refMatcapTexture.context({ getUV: () => matcapUV.mul(vec2(1, -1)).add(vec2(0, 1)) }); // VRMXG patch 1: variadic mul/add mirrored U',
  ],
  [
    'import { float as float2, modelViewPosition, normalView as transformedNormalView2 } from "three/tsl"; // VRMXG patch: r187 removed transformedNormalView (pixiv/three-vrm#1890)',
    'import { float as float2, positionView, normalView as transformedNormalView2 } from "three/tsl"; // VRMXG patch: r187 removed transformedNormalView (pixiv/three-vrm#1890); patch 2: positionView',
  ],
  [
    'const viewDir = modelViewPosition.normalize();',
    'const viewDir = positionView.normalize(); // VRMXG patch 2: per-fragment, not the object origin (modelViewPosition)',
  ],
  [
    'parametricRim.add(matcap).mul(rimMultiply).mul(mix(vec3(1), vec3(0), rimLightingMix))',
    'parametricRim.add(matcap).mul(rimMultiply).mul(mix(vec3(1), BRDF_Lambert({ diffuseColor: context.irradiance }), rimLightingMix)) // VRMXG patch 3: ambient in the rim mix, as GLSL',
  ],
];

let text = fs.readFileSync(src, 'utf8');
const missing = loadEdits.filter(([from]) => !text.includes(from));
if (missing.length) {
  console.error(`patch-three-vrm: @pixiv/three-vrm ${pkg.version} no longer has the expected imports:\n` + missing.map(([f]) => '  ' + f).join('\n'));
  process.exit(1);
}
if (process.argv.includes('--check')) { console.log(`patch-three-vrm: ${pkg.version} matches`); process.exit(0); }
for (const [from, to] of loadEdits) text = text.replace(from, to);
const header = `// GENERATED by scripts/patch-three-vrm.mjs from @pixiv/three-vrm ${pkg.version} lib/nodes/index.module.js (MIT, pixiv Inc.).\n// Do not edit; see the script for the changes.\n`;
fs.mkdirSync(path.dirname(outFull), { recursive: true });
fs.writeFileSync(outLoad, header + text);
for (const [from, to] of fidelityEdits) {
  if (!text.includes(from)) { console.error('patch-three-vrm: fidelity edit no longer applies:\n  ' + from); process.exit(1); }
  text = text.replace(from, to);
}
fs.writeFileSync(outFull, header + text);
console.log(`patch-three-vrm: @pixiv/three-vrm ${pkg.version} → ${path.relative(web, outLoad)} (${loadEdits.length} edits), ${path.relative(web, outFull)} (+${fidelityEdits.length})`);
