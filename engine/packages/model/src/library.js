// Models (the "models" service): glTF files parsed once per file before the scene is instantiated (or
// before a runtime add), cloned into every Model node that uses them. Static: a Model's colliders come
// from the asset's KHR_physics data ("fromAsset", the default) on one fixed body at the node's pose;
// "trimesh" and "convex" generated colliders arrive with the editor (M1) and are reported as skipped.
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { Node } from '@vrmxg/core';
import { addAssetColliders } from '@vrmxg/physics';
import { readGLBJson } from './glb.js';

/** Parse a .glb from bytes; `stubTextures` skips image decoding (headless). */
export async function parseGLB(bytes, { stubTextures = false } = {}) {
  const loader = new GLTFLoader();
  if (stubTextures) loader.register((parser) => ({ name: 'vrmxg_stub_textures', loadTexture: () => Promise.resolve(null) }));
  const ab = bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength);
  const gltf = await loader.parseAsync(ab, '');
  return { scene: gltf.scene, json: readGLBJson(bytes) };
}

export class ModelLibrary {
  /**
   * @param {{ resolve: (ref: string) => Promise<Uint8Array> | Uint8Array, prefabs?: Map<string, any>, stubTextures?: boolean }} opts
   */
  constructor({ resolve, prefabs = new Map(), stubTextures = false }) {
    this.resolve = resolve; this.prefabs = prefabs; this.stubTextures = stubTextures;
    /** ref → { scene, json } */ this.files = new Map();
    /** node id → ref */ this.refs = new Map();
    /** @type {Array<{ node: string, skipped: string[] }>} */ this.skipped = [];
  }

  /** Load every Model a scene uses, prefab instances included. */
  async prepare(doc) {
    const walk = async (d, prefix, depth) => {
      if (depth > 16) return;
      const assets = new Map((d.assets ?? []).map((a) => [a.id, a]));
      for (const n of d.nodes) {
        const ref = assets.get(n.asset)?.ref;
        if (n.type === 'Model' && ref) await this.prepareNode(prefix + n.id, ref);
        else if (n.type === 'Instance' && ref && this.prefabs.has(ref)) await walk(this.prefabs.get(ref), `${prefix}${n.id}/`, depth + 1);
      }
    };
    await walk(doc, '', 0);
    return this;
  }

  /** Load one Model node's file (a runtime add). */
  async prepareNode(id, ref) {
    if (!this.files.has(ref)) this.files.set(ref, await parseGLB(await this.resolve(ref), { stubTextures: this.stubTextures }));
    this.refs.set(id, ref);
  }

  get(id) {
    const ref = this.refs.get(id);
    if (!ref) throw new Error(`model "${id}" isn't prepared: await models.prepare(doc) before instantiate`);
    return { ref, ...this.files.get(ref) };
  }
}

export class ModelNode extends Node {
  enterTree() {
    const lib = this.tree.services.get('models');
    if (!lib) throw new Error(`Model "${this.id}" needs the models service (installModels)`);
    const m = lib.get(this.id);
    this.model = m.scene.clone(true);
    this.model.name = `${this.id}:model`;
    this.object3d.add(this.model);
    const physics = this.tree.services.get('physics');
    const mode = this.props.colliders ?? 'fromAsset';
    if (physics && mode === 'fromAsset') {
      this.object3d.updateWorldMatrix(true, false);
      const r = addAssetColliders(physics, this, m.json);
      if (r.skipped.length) lib.skipped.push({ node: this.id, skipped: r.skipped });
    } else if (physics && mode !== 'none') lib.skipped.push({ node: this.id, skipped: [`colliders "${mode}" are generated by the editor (M1); none made`] });
  }
  exitTree() {
    const physics = this.tree.services.get('physics');
    if (physics && this.assetBody !== undefined) { physics.removeBody(this, this.assetBody); this.assetBody = undefined; }
    if (this.model) this.object3d.remove(this.model);
  }
}
