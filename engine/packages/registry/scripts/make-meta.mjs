// Writes src/vendor/ajv-meta-2020.js: the JSON Schema draft 2020-12 meta-schema compiled ahead of time by Ajv's
// standalone code generator (M6 W7, AB-T-0654 item 6). A project's declared behaviours are checked against it when
// they are declared, so a game build never compiles a schema at run time and runs under a Content Security Policy
// without 'unsafe-eval'.
//
//   node engine/packages/registry/scripts/make-meta.mjs           write it
//   node engine/packages/registry/scripts/make-meta.mjs --check   exit 1 when the file isn't what this writes (a test runs it)
//
// The generated code imports nothing: Ajv's standalone output asks for `require("ajv/dist/runtime/equal")` (for
// uniqueItems), which an ES module can't call and whose default export Node and bundlers read differently, so a JSON
// deep-equal of its own stands in for it (the meta-schema compares only JSON values).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { Ajv2020 } from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const here = import.meta.dirname;
export const META_FILE = path.join(here, '../src/vendor/ajv-meta-2020.js');
const ajvPkg = JSON.parse(fs.readFileSync(createRequire(import.meta.url).resolve('ajv/package.json'), 'utf8'));
const ajvLicence = fs.readFileSync(path.join(path.dirname(createRequire(import.meta.url).resolve('ajv/package.json')), 'LICENSE'), 'utf8').trim();

const EQUAL = 'const equal = (a, b) => { if (a === b) return true; if (typeof a !== typeof b || a === null || b === null || typeof a !== "object") return a !== a && b !== b; if (Array.isArray(a) !== Array.isArray(b)) return false; if (Array.isArray(a)) return a.length === b.length && a.every((x, i) => equal(x, b[i])); const ka = Object.keys(a), kb = Object.keys(b); return ka.length === kb.length && ka.every((k) => Object.hasOwn(b, k) && equal(a[k], b[k])); };';

export function metaSource() {
  // the options the scene validator compiles with (draft 2020-12, unknown keywords allowed, every error)
  const ajv = new Ajv2020({ strict: false, allErrors: true, code: { source: true, esm: true, lines: false } });
  let code = (standaloneCode.default ?? standaloneCode)(ajv, ajv.getSchema('https://json-schema.org/draft/2020-12/schema'));
  const req = /const (\w+) = require\("ajv\/dist\/runtime\/equal"\)\.default;?/;
  if (!req.test(code)) throw new Error('Ajv\'s standalone output no longer asks for runtime/equal the way this script expects: read it again');
  code = code.replace(req, `const $1 = equal;`);
  if (/require\(/.test(code)) throw new Error('Ajv\'s standalone output requires something else now: make it an ES module by hand first');
  const header = [
    `Generated by engine/packages/registry/scripts/make-meta.mjs (do not edit): the JSON Schema draft 2020-12 meta-schema`,
    `as Ajv ${ajvPkg.version} ships it, compiled ahead of time by Ajv's standalone code generator, so that checking a schema needs`,
    `no code generated at run time. Ajv's licence:`,
    '',
    ...ajvLicence.split('\n'),
  ].map((l) => (l ? `// ${l}` : '//')).join('\n');
  return `${header}\n/* eslint-disable */\n${EQUAL}\n${code.replace(/^"use strict";/, '')}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const src = metaSource();
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(META_FILE) ? fs.readFileSync(META_FILE, 'utf8') : '';
    if (now !== src) { console.error(`${path.relative(process.cwd(), META_FILE)} is not what make-meta.mjs writes: run it again`); process.exit(1); }
  } else {
    fs.mkdirSync(path.dirname(META_FILE), { recursive: true });
    fs.writeFileSync(META_FILE, src);
    console.log(`wrote ${path.relative(process.cwd(), META_FILE)} (${src.length} bytes)`);
  }
}
