// The studio's live edits (vrmxa-core edit/three/live.js) on the engine's own Character in the cafe.
import fs from 'node:fs'; import path from 'node:path';
import { installPortableMath } from '../../engine/packages/dmath/src/index.js';
import { loadRapier } from '../../engine/packages/physics/src/index.js';
import { loadSample, buildWorld } from '../../apps/playground/src/world.js';
import { vrmxaCore, PATHS } from '../../engine/packages/character/test/fixtures.mjs';
import { worldHashes, hashValue } from '../../engine/packages/snapshot/src/index.js';
import { createLiveEdits } from '../../../vrmxa-core/src/edit/three/live.js';
import { parseGlb } from '../../../vrmxa-core/src/glb.js';
import { readEdits } from '../../../vrmxa-core/src/edit/index.js';
installPortableMath();
const here = import.meta.dirname, content = path.resolve(here, '../../content/sample'), who = path.resolve(process.argv[2] ?? path.join(here, '../out/aiko.vrmxa'));
const bytes = async (ref) => new Uint8Array(fs.readFileSync(ref === 'characters/mira.vrmxa' ? who : path.join(content, ref)));
const sample = await loadSample(bytes);
const core = await vrmxaCore();
const closet = await import(PATHS.core.replace(/index\.js$/, 'closet/index.js'));
const W = await buildWorld(await loadRapier(), sample, { vrmxaCore: core, closet, behaviours: new Map(), stubTextures: true });
const m = W.tree.find('mira');
for (let i = 0; i < 30; i++) W.tree.step();
const bundle = await core.readBundle(fs.readFileSync(who));
const live = createLiveEdits(m.vrm, parseGlb(new Uint8Array(bundle.entries.get('avatar.vrm'))));
const inv = () => { let n = 0, sum = 0; m.vrm.scene.traverse((o) => { if (o.isSkinnedMesh) for (const b of o.skeleton.boneInverses) { n++; sum += b.elements.reduce((a, x) => a + Math.abs(x), 0); } }); return +sum.toFixed(3); };
const head = () => { m.object3d.updateMatrixWorld(true); const b = m.vrm.humanoid.getNormalizedBoneNode('head'); const v = b.getWorldPosition(b.position.clone()); return +v.y.toFixed(4); };
const before = { inv: inv(), head: head(), sim: hashValue(worldHashes(W.tree)) };
const t = performance.now();
const doc = JSON.parse(fs.readFileSync(path.join(here, 'edits.json'),'utf8')); doc.body = { height: 0.6, legLength: 0.4 }; doc.face = { headShape: 'heart', shapes: { noseSize: 0.5 } };
const r = live.apply(readEdits(doc).edits);
const ms = performance.now() - t;
for (let i = 0; i < 2; i++) W.tree.step();
console.log(JSON.stringify({ applied: r ?? 'ok', applyMs: +ms.toFixed(1), headBefore: before.head, headAfter: head(), invBefore: before.inv, invAfter: inv(), keys: Object.keys(live) }));
